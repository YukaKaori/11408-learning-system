package com.yuka.learning.content;

import com.yuka.learning.exam.syllabus.Syllabus;
import com.yuka.learning.exam.syllabus.SyllabusLoader;
import tools.jackson.databind.json.JsonMapper;

import java.io.IOException;
import java.io.PrintStream;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;

/**
 * The offline content check — the same validation the server runs at boot,
 * without a database or a server, plus the coverage report.
 *
 * <pre>
 * cd server
 * ./mvnw -q compile exec:java                                   # packs in the jar
 * ./mvnw -q compile exec:java -Dexec.args="--dir /path/to/packs" # plus a packs directory
 * ./mvnw -q compile exec:java -Dexec.args="--markdown ../content/COVERAGE.md"
 * </pre>
 *
 * Exits 1 when any pack is invalid, listing every problem.
 */
public final class ContentCheck {

    private ContentCheck() {
    }

    public static void main(String[] args) {
        String directory = null;
        Path markdown = null;
        for (int i = 0; i < args.length; i++) {
            switch (args[i]) {
                case "--dir" -> directory = args[++i];
                case "--markdown" -> markdown = Path.of(args[++i]);
                default -> {
                    System.err.println("Usage: ContentCheck [--dir <packs-dir>] [--markdown <report.md>]");
                    System.exit(2);
                }
            }
        }
        PrintStream out = new PrintStream(System.out, true, StandardCharsets.UTF_8);
        JsonMapper mapper = JsonMapper.builder().build();
        Syllabus syllabus = SyllabusLoader.load(mapper);
        List<PackSource.Loaded> packs = PackSource.select(PackSource.loadAll(mapper, directory));
        PackValidator.Result result = PackValidator.validate(syllabus,
                packs.stream().map(PackSource.Loaded::pack).toList());

        out.println("Content packs: " + packs.size());
        for (PackSource.Loaded pack : packs) {
            out.printf("  %-28s v%-3s %4d questions %3d groups %2d papers  (%s)%n", pack.pack().pack(),
                    pack.pack().version(), pack.pack().questionsOrEmpty().size(), pack.pack().groupsOrEmpty().size(),
                    pack.pack().papersOrEmpty().size(), pack.origin().wire());
        }
        if (!result.ok()) {
            out.println();
            out.println(result.errors().size() + " problem(s):");
            result.errors().forEach(error -> out.println("  ✗ " + error));
            System.exit(1);
        }
        String report = render(Coverage.of(syllabus, result.content()));
        out.println();
        out.print(report);
        if (markdown != null) {
            try {
                Files.writeString(markdown, report, StandardCharsets.UTF_8);
                out.println("Report written to " + markdown.toAbsolutePath());
            } catch (IOException e) {
                throw new UncheckedIOException(e);
            }
        }
    }

    /** The coverage report as markdown (also readable in a terminal). */
    static String render(Coverage.Report report) {
        StringBuilder md = new StringBuilder();
        md.append("# Question bank coverage\n\n");
        md.append("Generated by `ContentCheck` (`cd server && ./mvnw -q compile exec:java -Dexec.args=\"--markdown ../content/COVERAGE.md\"`). ")
                .append("Do not edit by hand.\n\n");
        md.append("**").append(report.questions()).append(" questions · ").append(report.groups())
                .append(" groups · ").append(report.libraryPapers()).append(" library papers**\n\n");
        md.append("| Paper | Questions | 考点 | Whole papers the bank can assemble | Library papers |\n");
        md.append("| --- | ---: | ---: | ---: | ---: |\n");
        for (Coverage.Paper paper : report.papers()) {
            md.append("| ").append(paper.subject()).append(" | ").append(paper.questions()).append(" | ")
                    .append(paper.points()).append(" | ").append(paper.wholePapers()).append(" | ")
                    .append(paper.libraryPapers()).append(" |\n");
        }
        for (Coverage.Paper paper : report.papers()) {
            md.append("\n## ").append(paper.subject()).append("\n\n");
            md.append("Questions per 考点 (a question counts for every 考点 it tests):\n\n");
            md.append("| Weight | 0 | 1–4 | 5–9 | 10–19 | 20–29 | 30+ |\n");
            md.append("| --- | ---: | ---: | ---: | ---: | ---: | ---: |\n");
            for (Map.Entry<Integer, int[]> entry : paper.depthByWeight().entrySet()) {
                md.append("| ").append(entry.getKey());
                for (int count : entry.getValue()) {
                    md.append(" | ").append(count);
                }
                md.append(" |\n");
            }
            if (!paper.thinnest().isEmpty()) {
                md.append("\nThinnest weight-3 考点: ");
                md.append(String.join(" · ", paper.thinnest().stream()
                        .map(thin -> thin.name() + " (" + thin.questions() + ")").toList()));
                md.append("\n");
            }
            md.append("\n| Section | Questions | Slot | Eligible | Fills |\n");
            md.append("| --- | ---: | --- | ---: | ---: |\n");
            for (Coverage.Section section : paper.sections()) {
                boolean first = true;
                for (Coverage.Slot slot : section.slots()) {
                    String shape = slot.scope() + " × " + slot.count()
                            + (slot.group() != null ? " (texts of " + slot.group() + ")" : "")
                            + (slot.total() != null ? " = " + format(slot.total()) + " pts" : "");
                    md.append("| ").append(first ? section.code() + " (" + section.fills() + " fills)" : "")
                            .append(" | ").append(first ? String.valueOf(section.questions()) : "")
                            .append(" | ").append(shape).append(" | ").append(slot.eligible())
                            .append(" | ").append(slot.fills()).append(" |\n");
                    first = false;
                }
            }
        }
        return md.toString();
    }

    private static String format(double value) {
        return value == Math.rint(value) ? String.valueOf((long) value) : String.valueOf(value);
    }
}
